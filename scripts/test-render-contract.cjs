function schemas(source) {
  return [...source.matchAll(/<script[^>]*type="application\/ld\+json"[^>]*>([\s\S]*?)<\/script>/g)].flatMap((m) => {
    const value = JSON.parse(m[1]); return value['@graph'] || [value];
  });
}
